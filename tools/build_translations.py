"""Validate local translation catalogs and bundle them without runtime network access."""
from __future__ import annotations

import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ("en", "es", "gl", "fr", "de", "it", "pt")


def build() -> None:
    catalogs = {language: json.loads((ROOT / "app/ui/locales" / f"{language}.json").read_text(encoding="utf-8"))
                for language in LANGUAGES}
    source = catalogs["es"]["messages"]
    for language, catalog in catalogs.items():
        if catalog["language"] != language or catalog["messages"].keys() != source.keys():
            raise ValueError(f"Incomplete translation catalog: {language}")
        for key, value in catalog["messages"].items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"Empty translation: {language}: {key}")
            if sorted(re.findall(r"\{\d+\}", key)) != sorted(re.findall(r"\{\d+\}", value)):
                raise ValueError(f"Invalid translation placeholders: {language}: {key}")
    output = ROOT / "app/ui/translations.js"
    output.write_text("'use strict';\n// Generated by tools/build_translations.py from local catalogs.\nwindow.PriveltoTranslations = "
                      + json.dumps(catalogs, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"Bundled {len(source)} messages in {len(catalogs)} languages")


if __name__ == "__main__":
    build()
